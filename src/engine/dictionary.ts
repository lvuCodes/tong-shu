export function en(zh: string): string {
  return TRANSLATIONS[zh] ?? "";
}

export function ganzhiPinyin(gz: string): string {
  return [...gz].map((c) => STEM_PINYIN[c] ?? BRANCH_PINYIN[c] ?? c).join(" ");
}

export function ganzhiEn(gz: string): string {
  return [...gz].map((c) => STEM_EN[c] ?? BRANCH_EN[c] ?? c).join(" ");
}

export function lunarDateEn(label: string, month: number, day: number): string {
  return `${label.startsWith("闰") ? "Leap " : ""}month ${Math.abs(month)}, day ${day}`;
}

export function nineStarEn(s: string): string {
  return [...s.slice(0, 3)]
    .filter((c) => c in NINE_STAR)
    .map((c) => NINE_STAR[c])
    .join(" ");
}
